"""Deterministic Stage 1 clinical fact layer.

The fact layer is generated by code from the nine validated input fields.  It
is supplied to the model as reference material and persisted beside the model
candidate; the model never owns these facts.
"""

from __future__ import annotations

from typing import Any

from .clinical_input import Stage1ClinicalInput

FACT_LAYER_VERSION = "stage1_clinical_fact_layer_v1"


def _fma_interpretation(score: float, maximum: int, label: str) -> str:
    if score <= 0:
        level = "运动任务表现明显受限"
    elif score >= maximum * 0.9:
        level = "运动任务表现较好"
    else:
        level = "运动任务表现存在不同程度受限"
    return f"{label}{score:g}/{maximum}；{level}。这只是功能任务评分，不能换算为肌力、ROM、感觉或疼痛结果。"


def _mas_interpretation(value: str) -> str:
    if value == "0":
        return "手MAS为0；被动活动时未见肌张力增高。"
    if value == "1+":
        return "手MAS为1+；被动活动时存在轻度肌张力增高。"
    return f"手MAS为{value}；它只表示被动活动时的肌张力/阻力观察结果，不能换算为肌力、感觉或主动运动能力。"


_BRUNNSTROM = {
    1: "Brunnstrom手功能第I期；当前分期信息由医生输入，不能扩展为未测量的肌力、ROM或感觉结论。",
    2: "Brunnstrom手功能第II期；当前分期信息由医生输入，不能扩展为未测量的肌力、ROM或感觉结论。",
    3: "Brunnstrom手功能第III期；手功能以共同运动模式为主。",
    4: "Brunnstrom手功能第IV期；当前分期信息由医生输入，不能扩展为未测量的肌力、ROM或感觉结论。",
    5: "Brunnstrom手功能第V期；当前分期信息由医生输入，不能扩展为未测量的肌力、ROM或感觉结论。",
    6: "Brunnstrom手功能第VI期；可出现更分离、更接近协调的运动。",
}


def build_stage1_fact_layer(clinical_input: Stage1ClinicalInput) -> dict[str, Any]:
    """Return code-owned facts for prompt context and report rendering."""

    return {
        "fact_layer_version": FACT_LAYER_VERSION,
        "patient_facts": {
            "sex": clinical_input.sex,
            "age": clinical_input.age,
            "diagnosis": clinical_input.diagnosis,
            "disease_course": clinical_input.disease_course,
            "paralysis_side": clinical_input.paralysis_side,
        },
        "clinical_scores": {
            "fma_wrist": clinical_input.fma_wrist,
            "fma_hand": clinical_input.fma_hand,
            "hand_mas": clinical_input.hand_mas,
            "brunnstrom_hand": clinical_input.brunnstrom_hand,
        },
        "standardized_interpretations": [
            _fma_interpretation(clinical_input.fma_wrist, 10, "FMA腕"),
            _fma_interpretation(clinical_input.fma_hand, 20, "FMA手"),
            _mas_interpretation(clinical_input.hand_mas),
            _BRUNNSTROM[clinical_input.brunnstrom_hand],
        ],
    }


def render_stage1_fact_card(clinical_input: Stage1ClinicalInput) -> str:
    """Render a short deterministic card that is appended to the user message."""

    layer = build_stage1_fact_layer(clinical_input)
    facts = layer["patient_facts"]
    scores = layer["clinical_scores"]
    lines = [
        "【程序固定临床事实卡】",
        "以下事实由程序根据医生输入生成；模型不得修改、重算或扩展：",
        f"患者基本资料：性别={facts['sex']}；年龄={facts['age']}；诊断={facts['diagnosis']}；病程={facts['disease_course']}；患侧={facts['paralysis_side']}。",
        f"临床评分：FMA腕={scores['fma_wrist']:g}/10；FMA手={scores['fma_hand']:g}/20；手MAS={scores['hand_mas']}；Brunnstrom手功能={scores['brunnstrom_hand']}期。",
        "标准化解释：",
    ]
    lines.extend(f"- {item}" for item in layer["standardized_interpretations"])
    lines.append("模型只能使用上述标准化解释，不能把它们转换成肌力、ROM、感觉、疼痛、ADL或其他未采集结论。")
    return "\n".join(lines)


def render_program_integrated_assessment(clinical_input: Stage1ClinicalInput) -> str:
    """Render the fact-only assessment for the advice-only protocol."""

    layer = build_stage1_fact_layer(clinical_input)
    interpretations = layer["standardized_interpretations"]
    visible = [
        interpretations[0].split("。", 1)[0],
        interpretations[1].split("。", 1)[0],
        interpretations[2].split("；", 1)[-1].split("。", 1)[0],
        interpretations[3].split("；", 1)[-1].split("。", 1)[0],
    ]
    sentence_one = "；".join(visible) + "。"
    return sentence_one + "训练重点为腕手主动控制和手指运动控制。"


__all__ = [
    "FACT_LAYER_VERSION",
    "build_stage1_fact_layer",
    "render_program_integrated_assessment",
    "render_stage1_fact_card",
]
